/**
 * SCULPX E-Billing — Standard API Envelope & Protocol Types
 * Shared across all REST endpoints between Frontend and Node.js + PostgreSQL Backend.
 */

export interface ApiSuccessResponse<T> {
  success: true;
  data: T;
  message?: string;
  meta?: ApiMeta;
}

export interface ApiErrorDetail {
  field?: string;
  issue: string;
  received?: unknown;
}

export interface ApiErrorPayload {
  code: string; // e.g. "VALIDATION_FAILED", "UNAUTHORIZED", "RESOURCE_NOT_FOUND"
  message: string;
  details?: ApiErrorDetail[] | Record<string, unknown>;
  timestamp?: string; // ISO 8601 UTC
}

export interface ApiErrorResponse {
  success: false;
  data: null;
  error: ApiErrorPayload;
}

export type ApiResponseContract<T> = ApiSuccessResponse<T> | ApiErrorResponse;

export interface ApiMeta {
  requestId?: string;
  timestamp?: string;
  serverVersion?: string;
}

export interface ApiPaginationMeta {
  page: number; // 1-indexed
  limit: number;
  totalItems: number;
  totalPages: number;
  hasNextPage: boolean;
  hasPrevPage: boolean;
}

export interface ApiPaginatedResponse<T> {
  success: true;
  data: {
    items: T[];
    pagination: ApiPaginationMeta;
  };
  meta?: ApiMeta;
}

export interface ApiPaginationQueryParams {
  page?: number;
  limit?: number;
  sortBy?: string;
  sortOrder?: "asc" | "desc";
}

export interface IdempotencyHeaders {
  "Idempotency-Key"?: string; // UUID v4 generated by client for mutating operations
}
